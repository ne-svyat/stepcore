package com.vasil.stepcore.vault

/**
 * Сравнение двух версий страницы. Чистый Kotlin, проверяется тестами.
 *
 * ЗАЧЕМ
 * -----
 * История нужна не для того, чтобы "откатить всё". Чаще нужен КУСОК из
 * старой версии: абзац, который зря переписал. Значит история обязана
 * показывать, ЧТО именно изменилось, а не просто список времён — иначе
 * пятьдесят одинаковых строк с датами бесполезны.
 *
 * ПОЧЕМУ НЕ НАСТОЯЩИЙ ПОСТРОЧНЫЙ DIFF
 * -----------------------------------
 * Алгоритм Майерса дал бы точные вставки и удаления по всему тексту, но
 * это сотни строк кода и заметное время на десяти тысячах символов.
 * Реальная правка почти всегда сосредоточена в одном месте: человек
 * дописывает в конец или переписывает абзац. Общее начало плюс общий
 * конец находят это место точно и мгновенно.
 *
 * Честная граница: если правки разбросаны по всей странице, подсветится
 * весь промежуток между первым и последним изменением. Это не ошибка, а
 * заявленное поведение — подсветка показывает ОБЛАСТЬ правки.
 */
object VaultDiff {

    /**
     * Область различия.
     *
     * @param start общее начало: до этого места версии совпадают.
     * @param oldEnd конец изменённого куска в СТАРОМ тексте.
     * @param newEnd конец изменённого куска в НОВОМ тексте.
     */
    class Region(val start: Int, val oldEnd: Int, val newEnd: Int) {
        val isEmpty: Boolean get() = start == oldEnd && start == newEnd
    }

    fun region(old: String, new: String): Region {
        val max = minOf(old.length, new.length)
        var p = 0
        while (p < max && old[p] == new[p]) p++
        // Хвост считаем навстречу, но не заходя за уже найденное начало:
        // иначе на тексте "аааа" -> "аа" границы перехлестнулись бы.
        var s = 0
        while (s < max - p && old[old.length - 1 - s] == new[new.length - 1 - s]) s++
        return Region(p, old.length - s, new.length - s)
    }

    /** Что видно в ленте истории рядом со временем. */
    fun summary(old: String, new: String): String {
        if (old == new) return "без изменений"
        val d = new.length - old.length
        val r = region(old, new)
        return when {
            d > 0 && r.start >= old.length -> "дописано " + plural(d)
            d > 0 -> "добавлено " + plural(d)
            d < 0 && r.newEnd >= new.length && r.oldEnd >= old.length -> "стёрт конец, " + plural(-d)
            d < 0 -> "убрано " + plural(-d)
            else -> "правка, " + plural(r.newEnd - r.start)
        }
    }

    /** Русские окончания. Мелочь, но "1 знаков" читается как небрежность. */
    fun plural(n: Int): String {
        val a = n % 100
        val b = n % 10
        val word = when {
            a in 11..14 -> "знаков"
            b == 1 -> "знак"
            b in 2..3 -> "знака"
            b == 4 -> "знака"
            else -> "знаков"
        }
        return "$n $word"
    }

    /** Время «12 минут назад» — понятнее, чем 14:07, когда сравниваешь версии. */
    fun ago(thenMs: Long, nowMs: Long): String {
        val s = (nowMs - thenMs) / 1000
        return when {
            s < 45 -> "только что"
            s < 90 -> "минуту назад"
            s < 3600 -> (s / 60).toInt().let { "$it мин назад" }
            s < 86400 -> (s / 3600).toInt().let { "$it ч назад" }
            s < 86400 * 7 -> (s / 86400).toInt().let { "$it дн назад" }
            else -> (s / 86400 / 7).toInt().let { "$it нед назад" }
        }
    }
}
