package com.vasil.stepcore.vault

import kotlin.math.pow

/**
 * Тепло заметки: насколько она сейчас живая. Чистый Kotlin, тесты до сборки.
 *
 * ЗАМЫСЕЛ
 * -------
 * Порядок по дате создания врёт: заметка, заведённая год назад и
 * дополняемая каждый день, важнее вчерашней, в которую больше не
 * заглядывали. Считать «всего просмотров» тоже врёт - тогда однажды
 * популярное висит наверху вечно.
 *
 * Здесь каждое касание добавляет тепла, а тепло само остывает. Заброшенное
 * опускается без всякого «удалить», активное всплывает без всякой ручной
 * закладки. Это ровно то, что просили: приоритет, который то растёт, то
 * падает.
 *
 * ПОЧЕМУ ЭКСПОНЕНТА, А НЕ СКОЛЬЗЯЩЕЕ ОКНО
 * ---------------------------------------
 * Окно «за последние 30 дней» требует хранить журнал касаний: тысяча
 * заметок на годы - это сотни тысяч строк. Экспоненте хватает ДВУХ чисел
 * на заметку: тепло и когда его считали. Пересчёт ленивый, при чтении.
 *
 * ЧТО ЛЕЖИТ ОТКРЫТО
 * -----------------
 * Тепло и его отметка времени - числа в базе, не шифротекст. По ним видно,
 * что какая-то заметка активна, но не какая именно и не о чём. Ровно как
 * уже открытые updatedMs и номера страниц - это цена за возможность
 * сортировать, не расшифровывая весь тайник.
 */
object VaultHeat {

    /**
     * Период полураспада: через неделю касание весит вдвое меньше.
     *
     * Неделя выбрана под ритм человека, который пишет каждый день: за это
     * время успевает смениться тема, но не успевает забыться работа. Число
     * одно, и его легко подкрутить, если жизнь покажет другое.
     */
    const val HALF_LIFE_MS = 7L * 24 * 60 * 60 * 1000

    /** Открыл почитать - слабый сигнал: открывают и случайно. */
    const val W_OPEN = 1f
    /** Дописал - сильный: правка это намерение, а не любопытство. */
    const val W_EDIT = 4f
    /** Завёл новую - самый сильный, но остынет как все прочие. */
    const val W_CREATE = 8f

    /** Потолок. Без него ежедневная заметка за год уходит в бесконечность
     *  и подавляет вообще всё остальное. */
    const val MAX_HEAT = 400f

    /** Остудить накопленное к моменту now. */
    fun decay(heat: Float, atMs: Long, nowMs: Long): Float {
        if (heat <= 0f) return 0f
        if (atMs <= 0L || nowMs <= atMs) return heat.coerceAtMost(MAX_HEAT)
        val periods = (nowMs - atMs).toDouble() / HALF_LIFE_MS
        val v = heat * 0.5.pow(periods).toFloat()
        return if (v < 0.01f) 0f else v.coerceAtMost(MAX_HEAT)
    }

    /** Остудить и добавить новое касание. */
    fun bump(heat: Float, atMs: Long, nowMs: Long, weight: Float): Float =
        (decay(heat, atMs, nowMs) + weight).coerceAtMost(MAX_HEAT)

    /**
     * Доля тепла от самого горячего: 0..1.
     *
     * Нужна для показа - толщины, яркости, порядка. Абсолютное число тепла
     * человеку ничего не говорит, а «вдвое живее соседа» говорит.
     */
    fun share(heat: Float, maxHeat: Float): Float =
        if (maxHeat <= 0f) 0f else (heat / maxHeat).coerceIn(0f, 1f)
}
