package com.vasil.stepcore

/**
 * ГДЕ ТЕЛЕФОН: карман, рука или рюкзак. Только предположение — на счёт
 * шагов не влияет и влиять не должно, пока не проверено на беге.
 *
 * ЗАЧЕМ. Все пороги проекта измерялись в ОДНОМ положении телефона и в
 * другом врут. Это доказано дважды:
 *   - AMP_RUN_FLOOR = 8 отделял бег от ходьбы по ровному, но ходьба под
 *     горку с телефоном в кармане (журнал 07.08, 21:05-21:12) дала
 *     3.0-3.2 Гц и удар выше порога;
 *   - пороги стража тряски мерились на кармане, а на руке разваливались.
 * Пока место телефона неизвестно, любой порог — лотерея.
 *
 * ОТКУДА ПОРОГИ. Измерены 10.08 на четырнадцати размеченных отрезках
 * ходьбы (асфальт, обычный и средне-быстрый темп, экран включён и
 * выключен). Медианы по отрезкам:
 *
 *   карман   провал 0.15-0.33 g   пик 3.67-8.14 g
 *   рюкзак   провал 0.37-0.45 g   пик 1.96-2.10 g
 *   рука     провал 0.77-1.05 g   пик 1.97-2.67 g
 *
 * Между рюкзаком и рукой по провалу зазор 0.45..0.77 — порог 0.60 стоит
 * в его середине. Между рюкзаком и карманом по пику зазор 2.10..3.67 —
 * порог 3.00 стоит в его середине. Оба числа взяты ИЗ ЗАЗОРОВ, а не
 * подобраны: правило даёт 14 совпадений из 14.
 *
 * ПОЧЕМУ ИМЕННО ПРОВАЛ И ПИК. Провал модуля к нулю задумывался как
 * признак фазы полёта при беге. На ходьбе он показал 0.15 g в кармане —
 * глубже, чем у смоделированного бега. Причина: в кармане телефон не
 * закреплён на теле и подлетает САМ, отдельно от человека. То есть
 * провал меряет свободное падение ТЕЛЕФОНА, а не полёт ТЕЛА. Как признак
 * бега он не годится; как признак крепления — превосходен, потому что
 * ровно это он и меряет.
 *
 * ГРАНИЦЫ ЧЕСТНОСТИ (назвать вслух, пока не проверено):
 *  - Корпус собран на ОДНОМ человеке, ОДНОМ телефоне, ОДНОЙ одежде.
 *    Другой карман (глубже, плотнее, куртка вместо штанов) сдвинет числа.
 *  - Корпус собран только на ХОДЬБЕ. Бег даёт другие ускорения, и
 *    пороги могут поехать. Проверка — следующая пробежка.
 *  - Рука с заблокированным экраном мерилась окнами (акселерометр в фоне
 *    работает не всё время), и там материала меньше.
 *  - Положений на деле больше трёх: пояс, нагрудный карман, фиксатор на
 *    плече. Класс отвечает "не знаю", а не подгоняет к ближайшему.
 *
 * Чистый Kotlin, ноль android.* — проверяется тестами до сборки.
 */
object PlacementGuess {

    enum class Where { UNKNOWN, POCKET, HAND, BACKPACK }

    fun ru(w: Where): String = when (w) {
        Where.POCKET -> "карман"
        Where.HAND -> "рука"
        Where.BACKPACK -> "рюкзак"
        Where.UNKNOWN -> "не знаю"
    }

    /**
     * @param dipG  минимум модуля за окно, в долях g
     * @param peakG максимум модуля за окно, в долях g
     * @param strength сила отклика автокорреляции: без ритма судить не о чем
     */
    fun of(dipG: Float, peakG: Float, strength: Float, periodMs: Int): Where {
        // Без ритма это не ходьба и не бег — гадать не о чем.
        if (strength < MIN_RHYTHM) return Where.UNKNOWN
        // ЗА ГРАНИЦЕЙ ПОВЕРКИ. Корпус собран только на ходьбе. Журнал 13.08
        // (бег, телефон ТОЧНО в руке): 45 замеров подряд с ответом «карман,
        // уверенность 100%». На беге рука машет сильнее, телефон в ней
        // подлетает не хуже, чем в кармане, и обе величины уезжают в
        // размеченный диапазон кармана. Правило обязано молчать там, где
        // его не поверяли, а не выдавать уверенный неверный ответ.
        if (periodMs in 1 until WALK_PERIOD_MIN_MS) return Where.UNKNOWN
        // Пик ниже собственного веса означает, что окно вообще не про
        // локомоцию: при любом шаге удар превышает g.
        if (peakG < 1.2f) return Where.UNKNOWN
        if (dipG >= DIP_HAND) return Where.HAND
        if (peakG >= PEAK_POCKET) return Where.POCKET
        return Where.BACKPACK
    }

    /** Насколько уверенно, 0..1. Ближе к порогу — ниже уверенность. */
    fun confidence(dipG: Float, peakG: Float, w: Where): Float {
        val m = when (w) {
            Where.HAND -> (dipG - DIP_HAND) / 0.25f
            Where.POCKET -> (peakG - PEAK_POCKET) / 1.5f
            Where.BACKPACK -> minOf((DIP_HAND - dipG) / 0.25f, (PEAK_POCKET - peakG) / 1.5f)
            Where.UNKNOWN -> return 0f
        }
        return m.coerceIn(0f, 1f)
    }

    /** Порог провала: середина измеренного зазора рюкзак(0.45)..рука(0.77). */
    const val DIP_HAND = 0.60f
    /** Порог пика: середина измеренного зазора рюкзак(2.10)..карман(3.67). */
    const val PEAK_POCKET = 3.00f
    /** Ниже этого отклика окно не считается локомоцией. */
    /** Ниже этого отклика окно не считается локомоцией.
     *  Поднято с 0.25 до 0.45 по эталону покоя 15.08: при полной
     *  неподвижности автокорреляция выдавала на шуме до 0.38. У настоящей
     *  ходьбы отклик 0.46-0.80, запас сохраняется. */
    const val MIN_RHYTHM = 0.45f

    /** Короче этого периода корпус не собирался: всё, что быстрее, —
     *  бег или быстрый шаг, а там пороги не поверены. Граница взята с
     *  запасом от самой быстрой измеренной ходьбы (503 мс). */
    const val WALK_PERIOD_MIN_MS = 450
}
